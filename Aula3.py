"""
Python = Linguagem de programação
Tipo de tipagem = Dimâmica / Forte
str -> string -> texto
Strings são textos que estão dentro de aspas
"""
print(1234)
""" o python por ser linguagem Dinâmica reconhece os números com inteiros"""

# Aspas simples
print('Marcio Nascimento')

# Aspas duplas
print("Marcio Nascimento")

# Escape
print("Marcio \"Nascimento")
"""o caracter \ escape indica para o inteerpretador não ler o proximo caracter
o que  permite que seja impresso a aspas dupla"""

# r
print(r"Marcio \"Nascimento\"")
"""com o caracter r antes das Aspas idica que eu quero que
os caracteres de \escape apareça no print"""

print("Marcio 'Barbosa' Nascimento")
# se eu quiser imprimir aspas simples começo com aspas Duplas

print('Marcio "Barbosa" Nascimento')
